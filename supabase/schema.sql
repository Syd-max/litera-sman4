create or replace function public.mark_loan_borrowed(p_loan_id uuid)
returns public.loans
language plpgsql
security definer
set search_path = ''
as $$
declare result public.loans; target_book uuid;
begin
  if not private.is_librarian() then raise exception 'not authorized'; end if;
  select book_id into target_book from public.loans where id = p_loan_id and status = 'APPROVED' for update;
  if target_book is null then raise exception 'invalid loan transition'; end if;
  update public.books set available_stock = available_stock - 1 where id = target_book and available_stock > 0;
  if not found then raise exception 'book is not available'; end if;
  update public.loans
  set status = 'BORROWED', borrowed_at = now(), due_at = now() + interval '7 days', processed_by = (select auth.uid())
  where id = p_loan_id returning * into result;
  return result;
end;
$$;

