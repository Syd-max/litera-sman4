create or replace function public.handle_new_student()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.raw_user_meta_data ->> 'registration_source' = 'LITERA_STUDENT' then
    insert into public.student_profiles (id, full_name, class_name, enrollment_year, major, email)
    values (
      new.id,
      trim(new.raw_user_meta_data ->> 'full_name'),
      trim(new.raw_user_meta_data ->> 'class_name'),
      (new.raw_user_meta_data ->> 'enrollment_year')::smallint,
      trim(new.raw_user_meta_data ->> 'major'),
      new.email
    )
    on conflict (id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_student();

-- Recover student accounts created before the profile trigger was installed.
insert into public.student_profiles (id, full_name, class_name, enrollment_year, major, email)
select
  users.id,
  trim(users.raw_user_meta_data ->> 'full_name'),
  trim(users.raw_user_meta_data ->> 'class_name'),
  (users.raw_user_meta_data ->> 'enrollment_year')::smallint,
  trim(users.raw_user_meta_data ->> 'major'),
  users.email
from auth.users as users
where users.raw_user_meta_data ->> 'registration_source' = 'LITERA_STUDENT'
  and users.email is not null
  and char_length(trim(users.raw_user_meta_data ->> 'full_name')) between 2 and 120
  and char_length(trim(users.raw_user_meta_data ->> 'class_name')) between 1 and 50
  and char_length(trim(users.raw_user_meta_data ->> 'major')) between 1 and 80
  and users.raw_user_meta_data ->> 'enrollment_year' ~ '^\d{4}$'
on conflict (id) do nothing;

