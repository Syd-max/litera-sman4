end;
$$;

create or replace function public.request_loan(p_book_id uuid)
returns public.loans
language plpgsql
security definer
set search_path = ''
as $$
declare result public.loans;
begin
  if not private.is_active_student() then raise exception 'active student account required'; end if;
  if not exists (select 1 from public.books where id = p_book_id and archived_at is null and available_stock > 0) then raise exception 'book is not available'; end if;
  if exists (
    select 1 from public.loans
    where student_id = (select auth.uid()) and book_id = p_book_id
      and status in ('PENDING', 'APPROVED', 'BORROWED', 'RETURN_REQUESTED')
  ) then raise exception 'active loan already exists'; end if;
  insert into public.loans (student_id, book_id)
  values ((select auth.uid()), p_book_id)
  returning * into result;
  return result;
end;
$$;

