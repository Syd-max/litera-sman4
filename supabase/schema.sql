create or replace function public.confirm_return(p_loan_id uuid)
returns public.loans
language plpgsql
security definer
set search_path = ''
as $$
declare result public.loans; target_book uuid; target_student uuid; started_at timestamptz;
begin
  if not private.is_librarian() then raise exception 'not authorized'; end if;
  select book_id, student_id, borrowed_at into target_book, target_student, started_at
  from public.loans where id = p_loan_id and status = 'RETURN_REQUESTED' for update;
  if target_book is null then raise exception 'invalid loan transition'; end if;
  update public.books set available_stock = available_stock + 1
  where id = target_book and available_stock < total_stock;
  if not found then raise exception 'invalid stock state'; end if;
  update public.loans set status = 'RETURNED', returned_at = now(), processed_by = (select auth.uid())
  where id = p_loan_id returning * into result;
  insert into public.reading_history (student_id, book_id, loan_id, borrowed_at, returned_at)
  values (target_student, target_book, p_loan_id, started_at, result.returned_at)
  on conflict (loan_id) do nothing;
  return result;
end;
$$;

create or replace function public.save_book(
  p_book_id uuid,
  p_isbn text,
  p_title text,
  p_authors text,
  p_publisher text,
  p_publish_year smallint,
  p_category_id bigint,
  p_synopsis text,
  p_total_stock integer,
  p_shelf_location text,
  p_cover_url text,
  p_open_library_key text
)
returns public.books
language plpgsql
security definer
set search_path = ''
as $$
declare result public.books; checked_out integer;
begin
  if not private.is_librarian() then raise exception 'not authorized'; end if;
  if p_total_stock < 0 then raise exception 'invalid stock'; end if;
  if p_book_id is null then
    insert into public.books (isbn, title, authors, publisher, publish_year, category_id, synopsis, total_stock, available_stock, shelf_location, cover_url, open_library_key, created_by)
    values (nullif(trim(p_isbn), ''), trim(p_title), trim(p_authors), nullif(trim(p_publisher), ''), p_publish_year, p_category_id, nullif(trim(p_synopsis), ''), p_total_stock, p_total_stock, trim(p_shelf_location), nullif(trim(p_cover_url), ''), nullif(trim(p_open_library_key), ''), (select auth.uid()))
    returning * into result;
  else
    select total_stock - available_stock into checked_out from public.books where id = p_book_id for update;
    if checked_out is null then raise exception 'book not found'; end if;
    if p_total_stock < checked_out then raise exception 'total stock below checked out copies'; end if;
    update public.books set
      isbn = nullif(trim(p_isbn), ''), title = trim(p_title), authors = trim(p_authors), publisher = nullif(trim(p_publisher), ''),
      publish_year = p_publish_year, category_id = p_category_id, synopsis = nullif(trim(p_synopsis), ''), total_stock = p_total_stock,
      available_stock = p_total_stock - checked_out, shelf_location = trim(p_shelf_location), cover_url = nullif(trim(p_cover_url), ''),
      open_library_key = nullif(trim(p_open_library_key), '')
    where id = p_book_id returning * into result;
  end if;
  return result;
end;
$$;

create or replace function public.save_book_details(
  p_book_id uuid,
  p_isbn text,
  p_title text,
  p_authors text,
  p_publisher text,
  p_publish_year smallint,
  p_category_id bigint,
  p_synopsis text,
  p_total_stock integer,
  p_shelf_location text,
  p_cover_url text,
  p_open_library_key text,
  p_inventory_number text,
  p_classification text,
  p_acquisition_source text,
  p_source_note text,
  p_source_file text,
  p_source_sheet text,
  p_source_row integer,
  p_source_data jsonb
)
returns public.books
language plpgsql
security definer
set search_path = ''
as $$
declare result public.books; checked_out integer;
begin
  if not private.is_librarian() then raise exception 'not authorized'; end if;
  if p_total_stock < 0 then raise exception 'invalid stock'; end if;
  if char_length(trim(coalesce(p_title, ''))) = 0 then raise exception 'title is required'; end if;
  if p_book_id is null then
    if p_source_file is not null and p_source_sheet is not null and p_source_row is not null then
      select * into result from public.books
      where source_file = p_source_file and source_sheet = p_source_sheet and source_row = p_source_row;
      if found then return result; end if;
    end if;
    insert into public.books (
      isbn, title, authors, publisher, publish_year, category_id, synopsis, total_stock, available_stock,
      shelf_location, cover_url, open_library_key, inventory_number, classification, acquisition_source,
      source_note, source_file, source_sheet, source_row, source_data, created_by
    ) values (
      nullif(trim(p_isbn), ''), trim(p_title), trim(coalesce(p_authors, '')), nullif(trim(p_publisher), ''),
      p_publish_year, p_category_id, nullif(trim(p_synopsis), ''), p_total_stock, p_total_stock,
      trim(coalesce(p_shelf_location, '')), nullif(trim(p_cover_url), ''), nullif(trim(p_open_library_key), ''),
      nullif(trim(p_inventory_number), ''), nullif(trim(p_classification), ''), nullif(trim(p_acquisition_source), ''),
      nullif(trim(p_source_note), ''), nullif(trim(p_source_file), ''), nullif(trim(p_source_sheet), ''),
      p_source_row, coalesce(p_source_data, '{}'::jsonb), (select auth.uid())
    ) returning * into result;
  else
    select total_stock - available_stock into checked_out from public.books where id = p_book_id for update;
    if checked_out is null then raise exception 'book not found'; end if;
    if p_total_stock < checked_out then raise exception 'total stock below checked out copies'; end if;
    update public.books set
      isbn = nullif(trim(p_isbn), ''), title = trim(p_title), authors = trim(coalesce(p_authors, '')),
      publisher = nullif(trim(p_publisher), ''), publish_year = p_publish_year, category_id = p_category_id,
      synopsis = nullif(trim(p_synopsis), ''), total_stock = p_total_stock,
      available_stock = p_total_stock - checked_out, shelf_location = trim(coalesce(p_shelf_location, '')),
      cover_url = nullif(trim(p_cover_url), ''), open_library_key = nullif(trim(p_open_library_key), ''),
      inventory_number = nullif(trim(p_inventory_number), ''), classification = nullif(trim(p_classification), ''),
      acquisition_source = nullif(trim(p_acquisition_source), ''), source_note = nullif(trim(p_source_note), ''),
      source_file = coalesce(nullif(trim(p_source_file), ''), source_file),
      source_sheet = coalesce(nullif(trim(p_source_sheet), ''), source_sheet),
      source_row = coalesce(p_source_row, source_row),
      source_data = coalesce(p_source_data, source_data)
    where id = p_book_id returning * into result;
  end if;
  return result;
end;
$$;

create or replace function public.archive_book(p_book_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_librarian() then raise exception 'not authorized'; end if;
  update public.books set archived_at = now() where id = p_book_id and archived_at is null;
  if not found then return false; end if;
  delete from public.favorites where book_id = p_book_id;
  delete from public.book_search_stats where book_id = p_book_id;
  return true;
end;
$$;

create or replace function public.restore_book(p_book_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_librarian() then raise exception 'not authorized'; end if;
  update public.books set archived_at = null where id = p_book_id and archived_at is not null;
  return found;
end;
$$;

-- Compatibility: older clients calling delete_book now archive instead of deleting data.
create or replace function public.delete_book(p_book_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  return public.archive_book(p_book_id);
end;
$$;

create or replace function public.record_book_searches(p_book_ids uuid[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_active_student() then raise exception 'active student account required'; end if;

  insert into public.book_search_stats (book_id, search_count, last_searched_at)
  select distinct requested.book_id, 1, now()
  from unnest(coalesce(p_book_ids, '{}'::uuid[])) as requested(book_id)
  join public.books on books.id = requested.book_id and books.archived_at is null
  limit 5
  on conflict (book_id) do update
  set search_count = public.book_search_stats.search_count + 1,
      last_searched_at = now();
end;
$$;

create or replace function public.librarian_dashboard_metrics()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select case when private.is_librarian() then jsonb_build_object(
    'total_books', (select count(*) from public.books where archived_at is null),
    'available_copies', (select coalesce(sum(available_stock), 0) from public.books where archived_at is null),
    'active_loans', (select count(*) from public.loans where status in ('APPROVED', 'BORROWED', 'RETURN_REQUESTED')),
    'pending_students', (select count(*) from public.student_profiles where status = 'PENDING')
  ) else null end;
$$;

